function FR.GroupName(group, lang)
	local key = GROUPS[group]
	local name = key and FR.L[key] or (tostring(group):gsub("^%+", ""):gsub("^RestedXP%s+", ""):gsub("^RXP%s+", ""))
	if lang and lang ~= FR:Language() and FR:Language() ~= "enUS" then
		name = string.format(FR.L["%s (English)"], name)
	end
	return name
end

-- "Speedrun Guide 1-22", "Schnellste Route 1-22", "15-30" -> "Level 1-22"
function FR.SubgroupName(sub)
	if not sub then return nil end
	local range = tostring(sub):match("(%d+%-%d+)")
	if range then return string.format(FR.L["Level %s"], range) end
	return (tostring(sub):gsub("^RestedXP%s+", ""):gsub("^RXP%s+", ""))
end
