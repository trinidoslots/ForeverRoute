local LANGUAGE_OF_CLIENT = { deDE = "deDE", esES = "esES", esMX = "esES", frFR = "frFR", ptBR = "ptBR", zhCN = "zhCN" }
local KNOWN = {}
for _, l in ipairs(FR.LANGUAGES) do KNOWN[l[1]] = true end

-- The guide language that matches the game client (English for every other client).
function FR.ClientLanguage()
	return LANGUAGE_OF_CLIENT[clientLocale] or "enUS"
end

-- The languages offered in the settings: Chinese only on a Chinese client (any other client has
-- no font with those characters).
function FR.OfferedLanguages()
	local list = {}
	for _, l in ipairs(FR.LANGUAGES) do
		if l[1] ~= "zhCN" or FR.ClientLanguage() == "zhCN" then list[#list + 1] = l end
	end
	return list
end

-- "enUS", "deDE", "esES", "frFR", "ptBR" or "zhCN", from the setting ("auto" follows the game client).
function FR:Language()
	local pick = ForeverRouteDB and ForeverRouteDB.language or "auto"
	if pick == "auto" or not KNOWN[pick] then return FR.ClientLanguage() end
	return pick
end

FR.L = setmetatable({}, { __index = function(_, key)
	local t = TABLES[FR:Language()]
	return (t and t[key]) or key
end })

local registry = {}

-- Sets a widget's text now and whenever the language changes.
-- fmt (optional) receives the translated text and returns the final text.
function FR:Loc(widget, key, fmt)
	registry[#registry + 1] = { widget, key, fmt }
	local text = FR.L[key]
	widget:SetText(fmt and fmt(text) or text)
	return widget
end

function FR:ApplyLocale()
	for _, r in ipairs(registry) do
		local text = FR.L[r[2]]
		r[1]:SetText(r[3] and r[3](text) or text)
	end
end

