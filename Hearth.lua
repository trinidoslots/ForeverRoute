-- Where the hearthstone is bound, and what to do when a guide's "Hearth to <place>" step does not fit.
--
-- RestedXP's guides assume the hearthstone sits at the inn the guide last told you to set it at. A
-- player who set it somewhere else (or who never did) must not be told to hearth to a place it does
-- not lead to, and must not be left without a way to get there:
--   * ".bindlocation" lines compare the bound place by its name (FR.BindVerdict), also with the place the
--     step names and the place saved when the hearthstone was set;
--   * a "Hearth to <place>" step without such a line gets one when the place is known (FR.HEARTH_AREAS,
--     generated by tools/Audit-Guides.js from the guarded steps of the guides);
--   * in front of every hearthstone step a travel step is added (Parser.lua, FR.AddHearthFallbacks) that is
--     only shown while the hearthstone cannot be used, and leads to where the guide goes on.
local _, ns = ...
local FR = ns.FR

-- "The Drag", "Light's Hope Chapel." -> "drag", "lights hope chapel"
local function Norm(s)
	s = FR.Plain and FR.Plain(s)
	if type(s) ~= "string" then return nil end
	s = s:lower():gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""):gsub("[%p]", ""):gsub("^the ", ""):gsub("%s+", " ")
	s = s:gsub("^%s+", ""):gsub("%s+$", "")
	return s ~= "" and s or nil
end
FR.NormPlace = Norm

local function Same(a, b)
	if a == b then return true end
	if #a >= 4 and #b >= 4 and (a:find(b, 1, true) or b:find(a, 1, true)) then return true end
	return false
end

-- The place named in a step's text: "Hearth to Orgrimmar" -> "Orgrimmar".
function FR.HearthPlace(text)
	if type(text) ~= "string" then return nil end
	local place = text:match("[Hh]earth%s+to%s+([^%.,]+)") or text:match("Astral Recall%s+to%s+([^%.,]+)")
	if not place then return nil end
	place = place:gsub("%s+if%s.*$", ""):gsub("%s+and%s.*$", ""):gsub("%s+after%s.*$", ""):gsub("%s+once%s.*$", "")
	place = place:gsub("^%s+", ""):gsub("%s+$", "")
	return place ~= "" and place or nil
end

-- Saved when the hearthstone is set (the player stands in the inn then): what the game calls the place,
-- the area and the zone. Only used while GetBindLocation still says the same.
local function Saved()
	return ForeverRouteCharDB and ForeverRouteCharDB.bind
end

function FR.RecordBind()
	if not (ForeverRouteCharDB and GetBindLocation) then return end
	local text = FR.SafeText(GetBindLocation)
	if text == "" then return end
	local rec = { text = text }
	local old = Saved()
	if old and old.text == text then rec = old end   -- same place as before (login): keep what we know
	if FR.hearthJustBound then
		rec.sub, rec.zone = FR.SafeText(GetSubZoneText), FR.SafeText(GetZoneText)
		rec.real = FR.SafeText(GetRealZoneText)
		FR.hearthJustBound = nil
	end
	ForeverRouteCharDB.bind = rec
end

-- true = the hearthstone is bound to the place, false = bound elsewhere, nil = cannot tell.
-- `area` = the area id of a ".bindlocation" line (or nil), `place` = the name a step gives (or nil).
function FR.BindVerdict(area, place)
	if not GetBindLocation then return nil end
	local bound = Norm(FR.SafeText(GetBindLocation))
	if not bound then return nil end
	local want = {}
	local name = area and FR.AreaName and FR.AreaName(area)
	if name then want[#want + 1] = Norm(name) end
	if place then want[#want + 1] = Norm(place) end
	if #want == 0 then return nil end
	local have = { bound }
	local rec = Saved()
	if rec and rec.text and Norm(rec.text) == bound then
		for _, k in ipairs({ "sub", "zone", "real" }) do
			if rec[k] and rec[k] ~= "" then have[#have + 1] = Norm(rec[k]) end
		end
	end
	for _, w in ipairs(want) do
		for _, h in ipairs(have) do
			if w and h and Same(w, h) then return true end
		end
	end
	return false
end

-- Is the hearthstone not usable for the step `e` (a "hsfallback" condition): bound elsewhere, or still cooling down.
function FR.HearthUnusable(e)
	if not FR:Get("hearthFallback") then return false end
	if FR.BindVerdict(e.area, e.place) == false then return true end
	local start, duration = FR.Cooldown("item", 6948)
	if start and duration and duration > 0 and start + duration - GetTime() > 2 then return true end
	return false
end

-- /fr bind: what the game and the guide say about the hearthstone (for bug reports).
function FR:PrintBind()
	local bound = GetBindLocation and FR.SafeText(GetBindLocation) or ""
	self:Print(string.format("GetBindLocation() = '%s'", bound))
	local rec = Saved()
	if rec then
		self:Print(string.format("saved when set: text='%s' area='%s' zone='%s'", tostring(rec.text), tostring(rec.sub), tostring(rec.zone)))
	end
	local g = self.current
	if not (g and g.steps) then return end
	local shown = 0
	for _, s in ipairs(g.steps) do
		for _, e in ipairs(s.elements) do
			if e.cond == "bindlocation" or e.cond == "hsfallback" then
				local verdict = FR.BindVerdict(e.area, e.place)
				self:Print(string.format("step %d %s area=%s name='%s' place='%s' -> %s%s", s.idx or 0, e.cond, tostring(e.area),
					tostring(e.area and FR.AreaName(e.area)), tostring(e.place),
					verdict == nil and "cannot tell (step stays as the guide has it)" or (verdict and "bound there" or "bound elsewhere"),
					e.generated and " [added by ForeverRoute]" or ""))
				shown = shown + 1
				if shown >= 40 then self:Print("...") return end
			end
		end
	end
end
